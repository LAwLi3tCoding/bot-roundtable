"""Generate explicitly requested local launchers; never read instance credentials."""

from pathlib import Path
import os
import plistlib
import shlex
import shutil


def create_launcher(output, state, name, python, runtime):
    """Create a new bundle only; paths and runtime identity are fixed at generation."""
    target = Path(output).expanduser().absolute()
    if target.suffix != ".app":
        raise ValueError("launcher_output_requires_app_suffix")
    # mkdir must fail for existing bundles/symlinks, avoiding destructive replacement.
    target.mkdir(mode=0o700)
    try:
        executable_dir = target / "Contents" / "MacOS"
        executable_dir.mkdir(parents=True, mode=0o700)
        argv = [
            str(Path(python).absolute()),
            str(Path(runtime).absolute()),
            "ui",
            "--state-dir",
            str(Path(state).expanduser().absolute()),
            "--name",
            name,
        ]
        launcher = executable_dir / "launcher"
        launcher.write_text("#!/bin/sh\nexec " + shlex.join(argv) + " >/dev/null 2>&1\n")
        launcher.chmod(0o700)
        with (target / "Contents" / "Info.plist").open("wb") as handle:
            plistlib.dump(
                {
                    "CFBundleExecutable": "launcher",
                    "CFBundleIdentifier": "local.roundtable.ui",
                    "CFBundleName": "Bot Roundtable",
                    "CFBundlePackageType": "APPL",
                    "CFBundleVersion": "1",
                    "LSUIElement": True,
                },
                handle,
            )
    except BaseException:
        shutil.rmtree(target)
        raise
    return {"ok": True, "launcher": str(target), "installed": False}


CLIENT_MARKER = "# bot-roundtable client wrapper; generated by install-client, rerun to update"


def install_client_command(output, state, name, python, runtime):
    """Write a tiny sh wrapper with fixed paths; replaces only a wrapper it generated."""
    target = Path(output).expanduser().absolute()
    if target.is_symlink() or (target.exists() and not target.is_file()):
        raise FileExistsError("client_output_not_a_regular_file")
    if target.exists() and CLIENT_MARKER not in target.read_text(errors="replace"):
        raise FileExistsError("client_output_exists_not_generated_by_roundtable")
    argv = [
        str(Path(python).absolute()),
        str(Path(runtime).absolute()),
        "client",
        "--state-dir",
        str(Path(state).expanduser().absolute()),
        "--name",
        name,
    ]
    text = "#!/bin/sh\n" + CLIENT_MARKER + "\nexec " + shlex.join(argv) + ' "$@"\n'
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_name("." + target.name + ".tmp-" + str(os.getpid()))
    try:
        temporary.write_text(text)
        temporary.chmod(0o700)
        os.replace(temporary, target)
    finally:
        temporary.unlink(missing_ok=True)
    return {"ok": True, "client": str(target)}
