"""Generate explicitly requested local launchers; never read instance credentials."""

from pathlib import Path
import os
import plistlib
import shlex
import shutil
import subprocess
import sys
import tempfile

ICON_SVG = Path(__file__).resolve().parent / "assets" / "roundtable-icon.svg"
ICON_TOOLS = ("qlmanage", "sips", "iconutil")


def build_icns(svg, resources):
    """Best effort, macOS only: render the SVG, size it with sips and pack it with iconutil.

    Returns the icon file name, or None when the platform or tools are missing or a step fails;
    the launcher then keeps the default icon.
    """
    if sys.platform != "darwin" or not svg.exists():
        return None
    if not all(shutil.which(tool) for tool in ICON_TOOLS):
        return None

    def run(*argv):
        subprocess.run(argv, capture_output=True, check=True, timeout=60)

    try:
        with tempfile.TemporaryDirectory() as temporary:
            work = Path(temporary)
            run("qlmanage", "-t", "-s", "1024", "-o", str(work), str(svg))
            master = work / (svg.name + ".png")
            iconset = work / "AppIcon.iconset"
            iconset.mkdir()
            for size in (16, 32, 128, 256, 512):
                for scale, suffix in ((1, ""), (2, "@2x")):
                    pixels = str(size * scale)
                    name = f"icon_{size}x{size}{suffix}.png"
                    run("sips", "-z", pixels, pixels, str(master), "--out", str(iconset / name))
            resources.mkdir(parents=True, exist_ok=True, mode=0o700)
            run("iconutil", "-c", "icns", str(iconset), "-o", str(resources / "AppIcon.icns"))
    except (OSError, subprocess.SubprocessError):
        return None
    return "AppIcon.icns" if (resources / "AppIcon.icns").exists() else None


def launcher_script(argv, log_dir=None, search_path=None):
    """sh body: run `ui --autostart`, appending its JSON result to a private launcher log.

    Finder starts apps with a minimal PATH, so the generating shell's PATH is kept to find
    tunnel-client. Output goes to /dev/null only when no log directory can be created.
    """
    lines = ["#!/bin/sh", "umask 077"]
    if search_path:
        lines.append("PATH=" + shlex.quote(search_path) + "; export PATH")
    command = "exec " + shlex.join(argv)
    if log_dir:
        directory = shlex.quote(str(log_dir))
        log = shlex.quote(str(Path(log_dir) / "ui-launcher.log"))
        lines += [
            f"if mkdir -p {directory} 2>/dev/null; then",
            f"  date '+%Y-%m-%dT%H:%M:%S%z' >>{log} 2>/dev/null",
            f"  {command} >>{log} 2>&1",
            "fi",
        ]
    lines.append(command + " >/dev/null 2>&1")
    return "\n".join(lines) + "\n"


def create_launcher(output, state, name, python, runtime, log_dir=None, search_path=None):
    """Create a new bundle only; paths and runtime identity are fixed at generation."""
    target = Path(output).expanduser().absolute()
    if target.suffix != ".app":
        raise ValueError("launcher_output_requires_app_suffix")
    # mkdir must fail for existing bundles/symlinks, avoiding destructive replacement.
    target.mkdir(mode=0o700)
    try:
        executable_dir = target / "Contents" / "MacOS"
        executable_dir.mkdir(parents=True, mode=0o700)
        argv = [
            str(Path(python).absolute()),
            str(Path(runtime).absolute()),
            "ui",
            "--state-dir",
            str(Path(state).expanduser().absolute()),
            "--name",
            name,
            "--autostart",
        ]
        launcher = executable_dir / "launcher"
        launcher.write_text(launcher_script(argv, log_dir, search_path))
        launcher.chmod(0o700)
        info = {
            "CFBundleExecutable": "launcher",
            "CFBundleIdentifier": "local.roundtable.ui",
            "CFBundleName": "Bot Roundtable",
            "CFBundlePackageType": "APPL",
            "CFBundleVersion": "1",
            "LSUIElement": True,
        }
        icon = build_icns(ICON_SVG, target / "Contents" / "Resources")
        if icon:
            info["CFBundleIconFile"] = icon
        with (target / "Contents" / "Info.plist").open("wb") as handle:
            plistlib.dump(info, handle)
    except BaseException:
        shutil.rmtree(target)
        raise
    return {"ok": True, "launcher": str(target), "installed": False}


CLIENT_MARKER = "# bot-roundtable client wrapper; generated by install-client, rerun to update"


def install_client_command(output, state, name, python, runtime):
    """Write a tiny sh wrapper with fixed paths; replaces only a wrapper it generated."""
    target = Path(output).expanduser().absolute()
    if target.is_symlink() or (target.exists() and not target.is_file()):
        raise FileExistsError("client_output_not_a_regular_file")
    if target.exists() and CLIENT_MARKER not in target.read_text(errors="replace"):
        raise FileExistsError("client_output_exists_not_generated_by_roundtable")
    argv = [
        str(Path(python).absolute()),
        str(Path(runtime).absolute()),
        "client",
        "--state-dir",
        str(Path(state).expanduser().absolute()),
        "--name",
        name,
    ]
    text = "#!/bin/sh\n" + CLIENT_MARKER + "\nexec " + shlex.join(argv) + ' "$@"\n'
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_name("." + target.name + ".tmp-" + str(os.getpid()))
    try:
        temporary.write_text(text)
        temporary.chmod(0o700)
        os.replace(temporary, target)
    finally:
        temporary.unlink(missing_ok=True)
    return {"ok": True, "client": str(target)}
